fn in_ranges(character: char, ranges: &[(u32, u32)]) -> bool {
    let code = character as u32;
    ranges
        .binary_search_by(|&(start, end)| {
            if code < start {
                core::cmp::Ordering::Greater
            } else if code > end {
                core::cmp::Ordering::Less
            } else {
                core::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

pub(super) fn is_unassigned(character: char) -> bool {
    in_ranges(character, RFC3454_UNASSIGNED)
}

pub(super) fn is_combining_mark(character: char) -> bool {
    in_ranges(character, RFC4518_COMBINING_MARKS)
}
